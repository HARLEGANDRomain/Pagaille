import puppeteer from 'puppeteer-core'
const URL = 'http://localhost:4173/'
const out = []
const ok = (c, m) => out.push((c ? 'OK   ' : 'ECHEC ') + m)
const browser = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', headless: 'new', args: ['--no-sandbox', '--disable-gpu', '--block-new-web-views'] })
const page = await browser.newPage()
const errors = []
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message))
page.on('console', (m) => { if (m.type() === 'error' && !/fonts\.g|ERR_|Failed to load resource|net::/.test(m.text())) errors.push('console: ' + m.text()) })
await page.setRequestInterception(true)
page.on('request', (r) => (/^https?:\/\/(localhost|127\.0\.0\.1)/.test(r.url()) ? r.continue() : r.abort()))
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))
const txt = () => page.evaluate(() => document.body.innerText)
const click = async (sel) => { await page.waitForSelector(sel, { timeout: 4000 }); await page.click(sel) }
const fill = async (el, text) => { await el.focus(); await page.keyboard.down('Control'); await page.keyboard.press('KeyA'); await page.keyboard.up('Control'); await page.keyboard.type(text) }
const clickText = async (tag, text) => {
  const h = await page.evaluateHandle((tag, text) => [...document.querySelectorAll(tag)].find((e) => e.textContent.trim().startsWith(text)) ?? null, tag, text)
  const el = h.asElement(); if (!el) throw new Error('introuvable: ' + tag + ' ' + text); await el.click()
}

await page.setViewport({ width: 1280, height: 900 })
await page.goto(URL, { waitUntil: 'networkidle0' })
await sleep(500)
let t = await txt()
ok(/Bonjour|Bon après-midi|Bonsoir|Bonne nuit/.test(t) && t.includes('Romain'), 'accueil affiché avec le prénom')
ok(t.includes('Dune') && t.includes('Lire 10 minutes'), 'livre en cours et bouton de lecture')
ok(/Ta pile : \d/.test(t), 'pile en centimètres affichée')
ok(t.includes('Missions de la semaine'), 'missions affichées')
ok(t.includes('Les Lents Lecteurs'), 'résumé du cercle sur l’accueil')
await page.screenshot({ path: '/tmp/shots/01-accueil.png' })

// ---- bibliothèque + glisser-déposer
await page.goto(URL + '#bibliotheque'); await sleep(400)
t = await txt()
ok(t.includes('Ta bibliothèque') && t.includes('33 livres'), 'bibliothèque : 33 livres (7 + 26 pour tester les étagères pleines)')
await page.screenshot({ path: '/tmp/shots/02-bibliotheque.png' })
const dragTo = async (title, shelfKey) => {
  const sp = await page.$(`.shelf .spine[title="${title}"]`)
  const sh = await page.$(`.shelf[data-drop="${shelfKey}"]`)
  const a = await sp.boundingBox(), b = await sh.boundingBox()
  await page.mouse.move(a.x + a.width / 2, a.y + a.height / 2)
  await page.mouse.down()
  await page.mouse.move(a.x + a.width / 2 + 20, a.y + a.height / 2 + 10, { steps: 4 })
  await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2, { steps: 10 })
  await sleep(100)
  await page.screenshot({ path: '/tmp/shots/03-glisser.png' })
  await page.mouse.up()
  await sleep(500)
}
await dragTo('Fahrenheit 451', 'fini')
await page.evaluate(() => document.querySelector('.shelf[data-drop="fini"] .more-pile')?.click()); await sleep(200)
const inFini = await page.evaluate(() => [...document.querySelectorAll('.shelf[data-drop="fini"] .spine')].map((e) => e.getAttribute('title')))
ok(inFini.includes('Fahrenheit 451'), 'glisser-déposer : le livre passe sur l’étagère « Terminés »')
t = await txt()
ok(t.includes('Annuler'), 'glisser-déposer : message avec « Annuler »')
await clickText('.toast button', 'Annuler'); await sleep(500)
const back = await page.evaluate(() => [...document.querySelectorAll('.shelf[data-drop="cours"] .spine')].map((e) => e.getAttribute('title')))
ok(back.includes('Fahrenheit 451'), 'annuler remet le livre en cours')
await dragTo('Le Nom du vent', 'cours')
const still = await page.evaluate(() => [...document.querySelectorAll('.shelf[data-drop="aside"] .spine')].map((e) => e.getAttribute('title')))
ok(!still.includes('Le Nom du vent'), 'un livre abandonné déposé sur « En cours » quitte les étagères de côté')

// ---- fiche livre
await click('.shelf[data-drop="lire"] .spine'); await sleep(400)
t = await txt()
ok(t.includes('Don’t Make Me Think') && t.includes('Retirer de ma bibliothèque'), 'clic sur une tranche : fiche du livre')
await page.screenshot({ path: '/tmp/shots/04-fiche.png' })
await page.keyboard.press('Escape'); await sleep(300)
ok(!(await page.$('dialog[open]')), 'Échap ferme la fiche')

// ---- ajout manuel (la recherche réseau est coupée : doit échouer proprement)
await clickText('button', 'Ajouter un livre'); await sleep(300)
await page.type('dialog[open] input[type=search]', 'Hemingway'); await sleep(900)
t = await txt()
ok(/n’a pas répondu|Aucun résultat/.test(t), 'recherche indisponible : message clair, pas de plantage')
await page.screenshot({ path: '/tmp/shots/05-ajout.png' })
await clickText('button', 'Je ne le trouve pas'); await sleep(200)
await page.type('.modal input', 'Le Vieil Homme et la Mer', { delay: 0 }).catch(() => {})
const inputs = await page.$$('dialog[open] form input')
await fill(inputs[0], 'Le Vieil Homme et la Mer')
await inputs[1].type('Ernest Hemingway'); await inputs[2].type('150')
await clickText('dialog[open] button', 'Ajouter'); await sleep(600)
t = await txt()
ok(t.includes('Le Vieil Homme et la Mer') && t.includes('34 livres'), 'ajout manuel : le livre apparaît (34 livres)')

// ---- session de lecture
await page.goto(URL + '#aujourdhui'); await sleep(400)
await clickText('button', 'Lire 10 minutes'); await sleep(900)
t = await txt()
ok(t.includes('Mettre en pause') && /\d\d:\d\d/.test(t), 'scène de lecture : chrono visible')
await page.screenshot({ path: '/tmp/shots/06-scene.png' })
await clickText('#scene button', 'Mettre en pause'); await sleep(200)
ok((await txt()).includes('Reprendre'), 'pause : le bouton devient « Reprendre »')
await clickText('#scene button', 'J’ai fini de lire'); await sleep(300)
const numInputs = await page.$$('#scene input[type=number]')
await fill(numInputs[0], '12')
const pageInput = numInputs[1]
await fill(pageInput, '260')
await page.screenshot({ path: '/tmp/shots/07-scene-form.png' })
await clickText('#scene button', 'Enregistrer'); await sleep(900)
t = await txt()
ok(t.includes('C’est noté.') && /45 pages/.test(t), 'enregistrement : 45 pages gagnées (215 → 260)')
await page.screenshot({ path: '/tmp/shots/08-scene-fin.png' })
await clickText('#scene button', 'Revenir'); await sleep(500)
t = await txt()
ok(t.includes('Page 260 sur 830') || /Page 2[0-9]{2} sur/.test(t), 'l’accueil reflète la nouvelle page')
ok(/Rituel du jour tenu/.test(t), 'rituel du jour tenu (10 minutes minimum)')

// ---- missions : récupérer
const claims = await page.$$eval('.mission .btn.primary', (b) => b.length)
if (claims) { await page.click('.mission .btn.primary'); await sleep(500); ok((await txt()).includes('Récupéré'), 'mission : récupérer des signets') } else ok(true, 'aucune mission prête à récupérer (normal selon les missions de la semaine)')

// ---- découvrir
await page.goto(URL + '#decouvrir'); await sleep(400)
t = await txt()
ok(t.includes('Dans tes goûts') && t.includes('Du moment') && !t.includes('moins de 200 pages'), 'découvrir : sélection affichée, sans la section « moins de 200 pages »')
await page.screenshot({ path: '/tmp/shots/09-decouvrir.png' })
await clickText('button', 'Ajouter à ma pile'); await sleep(400)
const pre = await page.$eval('dialog[open] form input, dialog[open] input[aria-label="Chercher un livre"]', (i) => i.value).catch(() => '')
ok(pre.length > 2, 'découvrir : l’ajout pré-remplit le titre (' + pre + ')')
await page.keyboard.press('Escape'); await sleep(200)

// ---- cercle
await page.goto(URL + '#cercle'); await sleep(700)
t = await txt()
ok(t.includes('Les Lents Lecteurs') && t.includes('K7M2QX9A'), 'cercle : nom et code d’invitation')
ok(t.includes('Session ce soir 21h'), 'cercle : messages affichés')
await page.type('input[aria-label="Ton message"]', 'Je lis ce soir aussi')
await clickText('button', 'Envoyer'); await sleep(500)
ok((await txt()).includes('Je lis ce soir aussi'), 'cercle : message envoyé et reçu en direct')
await page.screenshot({ path: '/tmp/shots/10-cercle.png', fullPage: true })
await clickText('button', 'Sa bibliothèque'); await sleep(500)
ok(!!(await page.$('dialog[open]')), 'cercle : bibliothèque d’un ami')
await page.keyboard.press('Escape')

// ---- profil
await page.goto(URL + '#profil'); await sleep(400)
t = await txt()
ok(t.includes('Badges') && t.includes('Réglages'), 'profil affiché')
await page.screenshot({ path: '/tmp/shots/11-profil.png', fullPage: true })

// ---- mobile
await page.setViewport({ width: 390, height: 844, isMobile: true, hasTouch: true })
await page.goto(URL + '#aujourdhui'); await sleep(500)
await page.screenshot({ path: '/tmp/shots/12-mobile-accueil.png' })
await page.goto(URL + '#bibliotheque'); await sleep(500)
await page.screenshot({ path: '/tmp/shots/13-mobile-biblio.png' })
const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 2)
ok(!overflow, 'mobile : pas de débordement horizontal sur la bibliothèque')
await page.goto(URL + '#cercle'); await sleep(600)
ok(!(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 2)), 'mobile : pas de débordement horizontal sur le cercle')
await page.screenshot({ path: '/tmp/shots/14-mobile-cercle.png' })

// ---- connexion
await page.setViewport({ width: 390, height: 844 })
await page.evaluate(() => localStorage.setItem('mock-out', '1'))
await page.goto(URL); await sleep(500)
t = await txt()
ok(t.includes('Recevoir un code'), 'déconnecté : écran de connexion')
await page.screenshot({ path: '/tmp/shots/15-login.png' })
await clickText('button', 'Recevoir un code'); await sleep(200)
ok((await txt()).includes('pas complète') || (await txt()).includes('ne semble pas complète'), 'connexion : adresse vide refusée avec un message')
await page.type('input[type=email]', 'romain@exemple.fr')
await clickText('button', 'Recevoir un code'); await sleep(400)
ok((await txt()).includes('Un code est parti'), 'connexion : étape du code')
await page.type('input[inputmode=numeric]', '12345')
await clickText('button', 'Entrer'); await sleep(300)
ok((await txt()).includes('6 chiffres'), 'connexion : code trop court refusé')
await page.type('input[inputmode=numeric]', '6')
await clickText('button', 'Entrer'); await sleep(800)
ok((await txt()).includes('Romain'), 'connexion : code accepté, retour à la bibliothèque')

console.log(out.join('\n'))
console.log('\nErreurs JS:', errors.length ? '\n' + [...new Set(errors)].join('\n') : 'aucune')
await browser.close()
