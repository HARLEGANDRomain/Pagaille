import puppeteer from 'puppeteer-core'
const b = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', headless: 'new', args: ['--no-sandbox','--disable-gpu'] })
const p = await b.newPage(); await p.setViewport({width:1280,height:900})
await p.setRequestInterception(true); p.on('request', r=>/localhost/.test(r.url())?r.continue():r.abort())
const sleep=(ms)=>new Promise(r=>setTimeout(r,ms))
const T=()=>p.evaluate(()=>document.body.innerText)
await p.goto('http://localhost:4173/#aujourdhui',{waitUntil:'networkidle0'}); await sleep(400)
console.log('avant:', (await T()).split('\n').filter(l=>/Page \d/.test(l)).join('|'))
await p.evaluate(()=>[...document.querySelectorAll('button')].find(b=>b.textContent.trim().startsWith('Lire 10')).click()); await sleep(600)
await p.evaluate(()=>[...document.querySelectorAll('#scene button')].find(b=>b.textContent.includes('J’ai fini')).click()); await sleep(300)
const ins = await p.$$('#scene input'); console.log('inputs:', ins.length, await p.$$eval('#scene input', e=>e.map(i=>i.value)))
await ins[0].click({clickCount:3}); await ins[0].type('12')
await ins[1].click({clickCount:3}); await ins[1].type('260')
console.log('valeurs:', await p.$$eval('#scene input', e=>e.map(i=>i.value)))
await p.evaluate(()=>[...document.querySelectorAll('#scene button')].find(b=>b.textContent.includes('Enregistrer')).click()); await sleep(900)
console.log((await T()).split('\n').filter(l=>l.trim()).slice(-12).join('\n'))
await b.close()
